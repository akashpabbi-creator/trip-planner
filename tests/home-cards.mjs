// Home cards: groups, status lines and the one-time hint (demo mode, phone-sized screen).
// Run: node tests/home-cards.mjs
import { createRequire } from "module";
import { execSync, spawn } from "child_process";
import { mkdtempSync, writeFileSync } from "fs";
import { tmpdir } from "os";
import { join, dirname } from "path";
import { fileURLToPath } from "url";
const { chromium } = createRequire(import.meta.url)("/opt/node-tools/node_modules/playwright");
const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const dir = mkdtempSync(join(tmpdir(), "tp-homecards-"));
execSync(`cp -r "${root}/." "${dir}" && rm -rf "${dir}/.git"`);
writeFileSync(join(dir, "config.js"), "window.FIREBASE_CONFIG = null;\n");
const PORT = 8900 + Math.floor(Math.random() * 90);
const srv = spawn("python3", ["-m", "http.server", String(PORT), "--bind", "127.0.0.1"], { cwd: dir, stdio: "ignore" });
await new Promise((r) => setTimeout(r, 800));
let fails = 0;
const ok = (c, m) => { if (!c) fails++; console.log((c ? "  ok   " : "  FAIL ") + m); };
const b = await chromium.launch();
try {
  const p = await (await b.newContext({ viewport: { width: 390, height: 800 } })).newPage();
  const errors = [];
  p.on("pageerror", (e) => errors.push(e.message));
  await p.route(/^https?:\/\/(?!127\.0\.0\.1)/, (r) => r.fulfill({ status: 404, body: "" }));
  await p.goto(`http://127.0.0.1:${PORT}/`);
  await p.fill("#demoName", "Akash");
  await p.click("[data-action=signin]");
  await p.waitForSelector("[data-action=newTrip]");
  await p.evaluate(async () => {
    const S = window.__tripCtx.S, me = S.me;
    const iso = (n) => { const d = new Date(); d.setDate(d.getDate() + n); return d.toISOString().slice(0, 10); };
    const mk = (name, startDate, n, age) => S.store.createTrip({ name, destination: name, startDate, budget: 0, currency: "INR", days: Array.from({ length: n }, (_, i) => ({ id: name + i, title: "", base: "", notes: "" })), extras: [], owner: me.email, members: [me.email], memberNames: { [me.email]: me.name }, createdAt: Date.now(), updatedAt: Date.now() - age });
    await mk("Later", iso(67), 10, 1000);
    await mk("Soon", iso(5), 4, 2000);
    await mk("Now", iso(-2), 10, 3000);
    await mk("Undated", "", 3, 4000);
    await mk("Old", iso(-30), 5, 5000);
  });
  await p.waitForSelector(".home-group");
  await p.waitForTimeout(400);
  const txt = (sel) => p.$$eval(sel, (e) => e.map((x) => x.textContent.trim()));
  const heads = await txt(".home-group > h3, .home-group > summary");
  ok(heads.join("|") === "Coming up|Planning|Past (1)", "groups: " + heads.join(" | "));
  const coming = await p.$$eval("[data-group='Coming up'] .tc-title", (e) => e.map((x) => x.textContent.trim()));
  ok(coming.join(",") === "Now,Soon,Later", "coming up soonest first: " + coming);
  const st = await txt("[data-group='Coming up'] .tc-status");
  ok(st[0] === "Day 3 of 10 today" && st[1] === "In 5 days" && st[2] === "In 67 days", "status lines: " + st);
  ok((await txt("[data-group=Planning] .tc-status"))[0] === "No dates yet", "undated status");
  ok(!(await p.locator("[data-group=Past] .trip-card").first().isVisible()), "Past is folded");
  await p.click("[data-group=Past] summary");
  ok((await txt("[data-group=Past] .tc-status"))[0].startsWith("Ended 4 weeks ago"), "past status: " + (await txt("[data-group=Past] .tc-status")));
  const h = (await p.locator("[data-group='Coming up'] .trip-card").first().boundingBox()).height;
  ok(h < 130, "compact card height " + Math.round(h));
  ok(await p.locator(".tc-foot .av").count() >= 5, "member initials shown");
  ok(await p.locator("[data-home-hint]").count() === 1, "hint shown");
  await p.click("[data-action=hideHomeHint]");
  await p.reload();
  await p.waitForSelector(".home-group");
  ok(await p.locator("[data-home-hint]").count() === 0, "hint stays gone after reload");
  ok(errors.length === 0, "no page errors " + errors.join(";"));
  await p.screenshot({ path: "/tmp/home-light.png" });
  await p.emulateMedia({ colorScheme: "dark" });
  await p.waitForTimeout(400);
  await p.screenshot({ path: "/tmp/home-dark.png" });
  await p.setViewportSize({ width: 1200, height: 800 });
  await p.screenshot({ path: "/tmp/home-desktop-dark.png" });
  await p.emulateMedia({ colorScheme: "light" });
  await p.waitForTimeout(400);
  await p.screenshot({ path: "/tmp/home-desktop.png" });
} finally { await b.close(); srv.kill(); }
process.exit(fails ? 1 : 0);
